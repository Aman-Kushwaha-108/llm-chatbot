def on_send(_):
    message = message_box.value.strip()

    with chat_output:
        clear_output(wait=True)

        if not message:
            print("Enter a message first.")
            return

        if client is None:
            print("Configure your API key in Cell 1 first.")
            return

        result = chat(
            message,
            system_instruction=(
                system_box.value.strip()
                or DEFAULT_SYSTEM_INSTRUCTION
            ),
            temperature=temperature_slider.value,
            max_output_tokens=token_slider.value
        )

        if result["ok"]:
            display(Markdown("### Assistant"))
            print(result["response"])
            print("\nUsage:", result["usage"])
            message_box.value = ""
        else:
            print("Request failed:", result["error"])


