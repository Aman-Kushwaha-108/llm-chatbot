def on_usage(_):
    with dashboard_output:
        clear_output(wait=True)

        if not usage_records:
            print("No API usage recorded yet.")
            return

        df = pd.DataFrame(usage_records)
        display(df)

        total_input = int(df["input_tokens"].sum())
        total_output = int(df["output_tokens"].sum())

        print("\nTotal input tokens:", total_input)
        print("Total output tokens:", total_output)
        print("Total tokens:", total_input + total_output)

        if df["estimated_cost_usd"].notna().all():
            print(
                "Estimated cost: $",
                round(df["estimated_cost_usd"].sum(), 6)
            )
        else:
            print(
                "Cost not calculated. Configure current provider "
                "rates in Cell 1 to estimate costs."
            )

        plt.figure(figsize=(8, 4))
        plt.bar(
            ["Input tokens", "Output tokens"],
            [total_input, total_output]
        )
        plt.title("Token Usage")
        plt.ylabel("Tokens")
        plt.tight_layout()
        plt.show()

        df.to_csv("llm_api_usage_report.csv", index=False)
        print("Saved: llm_api_usage_report.csv")


