# JSON callback
# -----------------------------------------------

def on_json(_):
    text = message_box.value.strip()

    with chat_output:
        clear_output(wait=True)

        if not text:
            print("Enter text to convert into structured JSON.")
            return

        result = generate_structured_json(
            "Summarize and categorize the supplied text",
            text
        )

        if result["ok"]:
            print(json.dumps(
                result["data"],
                indent=2,
                ensure_ascii=False
            ))
            print("\nUsage:", result["usage"])
        else:
            print(result["error"])
            if "raw_output" in result:
                print(result["raw_output"])


