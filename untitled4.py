def approximate_tokens(text):
    """Rough estimate only; not an official tokenizer count."""
    return max(1, len(text) // 4) if text else 0


def estimate_cost(input_tokens, output_tokens):
    """
    Rates must be entered from current provider pricing.
    Rates are expressed in USD per million tokens.
    """
    if INPUT_COST_PER_MILLION is None or OUTPUT_COST_PER_MILLION is None:
        return None

    return (
        input_tokens * INPUT_COST_PER_MILLION
        + output_tokens * OUTPUT_COST_PER_MILLION
    ) / 1_000_000


def record_usage(response, elapsed, input_text, output_text):
    """Record usage metadata when the provider returns it."""
    metadata = getattr(response, "usage_metadata", None)

    input_tokens = getattr(metadata, "prompt_token_count", None)
    output_tokens = getattr(metadata, "candidates_token_count", None)
    total_tokens = getattr(metadata, "total_token_count", None)

    # Approximate counts only when API metadata is unavailable.
    if input_tokens is None:
        input_tokens = approximate_tokens(input_text)
    if output_tokens is None:
        output_tokens = approximate_tokens(output_text)
    if total_tokens is None:
        total_tokens = input_tokens + output_tokens

    cost = estimate_cost(input_tokens, output_tokens)

    usage_records.append({
        "model": MODEL_NAME,
        "input_tokens": input_tokens,
        "output_tokens": output_tokens,
        "total_tokens": total_tokens,
        "latency_seconds": round(elapsed, 3),
        "estimated_cost_usd": cost
    })

    return usage_records[-1]


# -----------------------------------------------
# Main LLM API function
# -----------------------------------------------

def call_llm(
    messages,
    system_instruction=DEFAULT_SYSTEM_INSTRUCTION,
    temperature=DEFAULT_TEMPERATURE,
    max_output_tokens=DEFAULT_MAX_OUTPUT_TOKENS,
    response_mime_type=None
):
    """
    messages format:
    [
        {"role": "user", "content": "..."},
        {"role": "assistant", "content": "..."}
    ]
    """

    if client is None:
        return {
            "ok": False,
            "error": "API client is not configured. Run Cell 1 and provide a valid key."
        }

    if not messages:
        return {"ok": False, "error": "At least one message is required."}

    if not 0 <= temperature <= 2:
        return {"ok": False, "error": "Temperature must be between 0 and 2."}

    if not 1 <= max_output_tokens <= 8192:
        return {"ok": False, "error": "Output token limit must be between 1 and 8192."}

    # Convert the conversation to Gemini's message format.
    contents = []

    for message in messages:
        role = message.get("role")
        content = str(message.get("content", ""))

        if role not in ("user", "assistant", "model"):
            return {"ok": False, "error": f"Unsupported role: {role}"}

        if not content.strip():
            continue

        sdk_role = "model" if role in ("assistant", "model") else "user"

        contents.append(
            types.Content(
                role=sdk_role,
                parts=[types.Part.from_text(text=content)]
            )
        )

    if not contents:
        return {"ok": False, "error": "No non-empty messages supplied."}

    config_args = {
        "system_instruction": system_instruction,
        "temperature": temperature,
        "max_output_tokens": max_output_tokens
    }

    if response_mime_type:
        config_args["response_mime_type"] = response_mime_type

    config = types.GenerateContentConfig(**config_args)

    input_text = "\n".join(
        str(message.get("content", "")) for message in messages
    )

    start = time.perf_counter()

    try:
        response = client.models.generate_content(
            model=MODEL_NAME,
            contents=contents,
            config=config
        )

        elapsed = time.perf_counter() - start
        output_text = response.text or ""

        if not output_text.strip():
            return {
                "ok": False,
                "error": "The API returned no text. Try a different prompt."
            }

        usage = record_usage(
            response, elapsed, input_text, output_text
        )

        return {
            "ok": True,
            "response": output_text,
            "usage": usage
        }

    except errors.APIError as error:
        code = getattr(error, "code", None)

        if code == 429:
            message = "Rate limit or quota reached. Check API usage and limits."
        elif code in (401, 403):
            message = "Authentication or permission error. Check the API key and access."
        elif code == 400:
            message = "Invalid request. Check the model, parameters, and prompt."
        else:
            message = f"API error ({code}): {str(error)}"

        return {"ok": False, "error": message}

    except Exception as error:
        return {
            "ok": False,
            "error": f"Unexpected error: {type(error).__name__}: {str(error)}"
        }


