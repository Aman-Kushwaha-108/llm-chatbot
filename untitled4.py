def generate_structured_json(task, text):
    prompt = f"""
Task: {task}

Input:
{text}

Return a JSON object with these fields:
- summary: string
- category: string
- keywords: list of strings
- uncertainty: string

Use only information supported by the input.
"""

    result = call_llm(
        [{"role": "user", "content": prompt}],
        temperature=0.1,
        max_output_tokens=400,
        response_mime_type="application/json"
    )

    if not result["ok"]:
        return result

    try:
        parsed = json.loads(result["response"])

        required = {"summary", "category", "keywords", "uncertainty"}
        if not required.issubset(parsed):
            raise ValueError("Missing required JSON fields.")

        if not isinstance(parsed["keywords"], list):
            raise ValueError("'keywords' must be a JSON array.")

        return {
            "ok": True,
            "data": parsed,
            "usage": result["usage"]
        }

    except (json.JSONDecodeError, ValueError) as error:
        return {
            "ok": False,
            "error": f"JSON validation failed: {error}",
            "raw_output": result["response"]
        }


